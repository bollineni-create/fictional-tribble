const store = {
  get(key, fallback) {
    try { return JSON.parse(localStorage.getItem(`slab:${key}`)) ?? fallback; } catch { return fallback; }
  },
  set(key, value) {
    try { localStorage.setItem(`slab:${key}`, JSON.stringify(value)); } catch { /* storage unavailable */ }
  },
};

